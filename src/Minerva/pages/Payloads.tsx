                                                        "p-3 rounded border",
                                                        step.step_success === true ? "bg-matrix/5 border-matrix/20" :
                                                        step.step_success === false ? "bg-red-500/5 border-red-500/20" :
                                                        "bg-ghost/5 border-ghost/20"
